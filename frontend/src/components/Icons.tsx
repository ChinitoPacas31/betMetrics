export function getSportIcon(sportKey: string, className = "h-4 w-4") {
  const normalized = (sportKey || "").toLowerCase();
  if (normalized.startsWith("soccer")) return <IconSoccer className={className} />;
  if (normalized.startsWith("basketball")) return <IconBasketball className={className} />;
  if (normalized.startsWith("americanfootball") || normalized.startsWith("aussierules") || normalized.startsWith("rugby")) {
    return <IconFootball className={className} />;
  }
  if (normalized.startsWith("baseball") || normalized.startsWith("cricket")) {
    return <IconBaseball className={className} />;
  }
  return <IconTrophy className={className} />;
}

